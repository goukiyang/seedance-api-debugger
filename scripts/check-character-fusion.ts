import assert from 'node:assert/strict';
import { defaults, generateBatch, refreshBoss, required, changeRow, missingRequired, bossRow, textFor, csvFor, parseSettings, reconcile, CONFIG } from '../src/lib/character-fusion/engine';

const settings = defaults();
settings.rules.source.find(t => t.label === '动物')!.status = 'exclude';
settings.rules.source.find(t => t.label === '植物')!.status = 'must';
settings.rules.mechanism[0].status = 'must';
settings.bossDimensions.push('equipment');
settings.rules.equipment[0].status = 'must';
settings.bossLocks.concept = true; settings.bossLocks.equipment = true;
settings.boss.equipment = settings.rules.equipment[0].label;
for (let seed = 1; seed <= 32; seed++) {
  const rows = generateBatch(settings, seed);
  assert.equal(rows.length, 16);
  assert(rows.every(r => r.category.source !== '动物'));
  for (const c of CONFIG) for (const label of required(settings, c.id)) assert(rows.some(r => r.category[c.id] === label));
  assert.equal(new Set(rows.map(r => r.category.source)).size, 11);
  assert.equal(new Set(rows.map(r => r.name)).size, 16);
  assert.equal(refreshBoss(settings, () => .8).boss.concept, settings.boss.concept);
  assert.equal(refreshBoss(settings, () => .8).boss.equipment, settings.boss.equipment);
  assert(rows.every(row => row.category.concept === settings.boss.concept && row.category.equipment === settings.boss.equipment));
  assert.deepEqual(missingRequired(settings, changeRow(settings, rows, rows[0].id, undefined, seed + 999)), []);
}
const restored = parseSettings(JSON.parse(JSON.stringify(settings)));
assert.equal(restored.bossLocks.concept, true);
const singleton = defaults(); singleton.bossDimensions = CONFIG.map(c => c.id);
for (const c of CONFIG) singleton.rules[c.id] = [{ label: c.tags[0], status: 'must' }];
const rows = generateBatch(singleton, 99);
assert.equal(new Set(rows.map(r => r.name)).size, 16);
assert(rows.some(r => r.category.equipment === singleton.rules.equipment[0].label));
const before = generateBatch(defaults(), 6);
const changed = changeRow(defaults(), before, before[0].id, { dimension: 'personality', value: '温柔保护型' }, 150)[0];
assert.deepEqual(changed.source, before[0].source); assert.deepEqual(changed.concept, before[0].concept); assert.deepEqual(changed.mechanism, before[0].mechanism); assert.deepEqual(changed.detail, before[0].detail);
const bossSettings = defaults(); bossSettings.bossLocks.source = true;
assert.equal(refreshBoss(bossSettings, () => .5).boss.source, bossSettings.boss.source);
assert.equal(bossRow(bossSettings, [], 88).category.source, bossSettings.boss.source);
singleton.requirementsEnabled = true; singleton.requirements = '全局要求测试';
assert(textFor(rows[0], singleton).includes('全局要求测试'));
assert(csvFor([{ ...rows[0], name: '=1+1' }], singleton).includes('"\'=1+1"'));
assert(rows.every(row => !/[\u3400-\u9fff]/.test(textFor(row, { requirements: defaults().requirements, lang: 'en' }))));
const bilingualRow = { ...rows[0], category: { ...rows[0].category, equipment: '防护装备类' }, detail: { ...rows[0].detail, equipment: '反向雨伞盾' } };
assert(textFor(bilingualRow, { requirements: defaults().requirements, lang: 'en' }).includes('reverse umbrella shield'));
bilingualRow.detail.equipment = '能反扣为浮力救生舱的肩盾';
assert(textFor(bilingualRow, { requirements: defaults().requirements, lang: 'en' }).includes('flotation rescue capsule'));
const custom = defaults();
for (const c of CONFIG) custom.rules[c.id] = [{ label: '__proto__', status: 'must' }];
assert.equal(generateBatch(custom, 12)[0].source.name, '__proto__');
const invalid = defaults(); invalid.rules.source.forEach(t => { t.status = 'exclude'; });
assert.throws(() => generateBatch(invalid), /全部排除/);
const capacity = defaults(); capacity.count = 4; capacity.rules.source.slice(0, 5).forEach(t => { t.status = 'must'; });
assert.throws(() => generateBatch(capacity), /超过/);
console.log('PASS: 32 batches; exclusions, required coverage, locks, domain diversity, unique names, single-dimension preservation, recipe roundtrip and validation. No model/network/database calls.');

const disabled = defaults(); disabled.requirements = '必须是紫色'; disabled.requirementsEn = 'Must be purple';
const sample = generateBatch(disabled, 212)[0];
assert(!textFor(sample, disabled).includes('必须是紫色'));
assert(!textFor(sample, { ...disabled, lang: 'en' }).includes('Must be purple'));
disabled.requirementsEnabled = true;
assert(textFor(sample, disabled).includes('必须是紫色'));
assert(textFor(sample, { ...disabled, lang: 'both' }).includes('Must be purple'));
const legacy = { ...disabled } as Record<string, unknown>; delete legacy.requirementsEnabled; delete legacy.cards; delete legacy.role; delete legacy.requirementsEn;
assert.equal(parseSettings(legacy).requirementsEnabled, false);
const extended = defaults(); extended.role = '配角';
extended.cards = [{ id: 'card-check', title: '叙事任务', titleEn: 'Narrative task', joined: true, locked: false, value: '守护', tags: [{ label: '守护', en: 'guardian', status: 'must' }, { label: '探索', en: 'explorer', status: 'default' }] }];
const extendedRows = generateBatch(extended, 13);
assert(extendedRows.some(r => r.cards?.some(c => c.label === '守护')));
assert(textFor(extendedRows[0], extended).includes('叙事任务'));
assert(textFor(extendedRows[0], { ...extended, lang: 'en' }).includes('supporting character'));
assert(!/[\u3400-\u9fff]/.test(textFor(extendedRows[0], { ...extended, lang: 'en' })));
assert.deepEqual(parseSettings(JSON.parse(JSON.stringify(extended))).cards, extended.cards);
extended.cards[0].joined = false;
assert(generateBatch(extended, 14).every(r => r.cards?.length === 0));
assert(generateBatch(defaults(), 15).every(r => !r.category.equipment && !r.category.signature));
console.log('PASS: requirement switch in both outputs; legacy recipes; custom bilingual cards participate only when joined; general character roles.');

const fixed = defaults(); fixed.bossLocks.source = true;
for (let seed = 1; seed <= 32; seed++) {
  const batch = generateBatch(fixed, seed);
  assert(batch.every(row => row.category.source === '动物'));
  assert.equal(changeRow(fixed, batch, batch[0].id, undefined, seed + 50)[0].category.source, '动物');
  assert.throws(() => changeRow(fixed, batch, batch[0].id, { dimension: 'source', value: '植物' }), /先解锁/);
}
fixed.rules.source.find(t => t.label === '植物')!.status = 'must';
assert.throws(() => generateBatch(fixed), /固定项与规则冲突/);
const lockedCard = defaults();
lockedCard.cards = [{ id: 'card-locked', title: '阵营', titleEn: 'Faction', joined: true, locked: true, value: '探索者', tags: [{ label: '守护者', en: 'guardian', status: 'default' }, { label: '探索者', en: 'explorer', status: 'default' }] }];
const cardBatch = generateBatch(lockedCard, 301);
assert(cardBatch.every(row => row.cards?.[0].label === '探索者'));
lockedCard.cards[0].value = '守护者';
assert.equal(changeRow(lockedCard, cardBatch, cardBatch[0].id, undefined, 302)[0].cards?.[0].label, '守护者');
lockedCard.cards[0].tags[1].status = 'must';
assert.throws(() => generateBatch(lockedCard), /固定项与规则冲突/);
const optionalFixed = defaults(); optionalFixed.bossDimensions.push('equipment'); optionalFixed.bossLocks.equipment = true;
assert(generateBatch(optionalFixed, 303).every(row => row.category.equipment === ''));
const excludedFixed = defaults(); excludedFixed.bossLocks.source = true;
excludedFixed.rules.source.find(t => t.label === '动物')!.status = 'exclude';
const unresolved = reconcile(excludedFixed);
assert.equal(unresolved.boss.source, '动物'); assert.equal(unresolved.bossLocks.source, true);
assert.throws(() => generateBatch(unresolved), /固定项与规则冲突/);
assert.equal(parseSettings(JSON.parse(JSON.stringify(unresolved))).bossLocks.source, true);
lockedCard.cards[0].tags[1].status = 'default'; lockedCard.cards[0].tags[0].status = 'exclude';
assert.throws(() => generateBatch(lockedCard), /固定项与规则冲突/);
console.log('PASS: batch/rewrite locks for built-in and custom cards; fixed vs required conflicts; fixed unused optional dimension.');
