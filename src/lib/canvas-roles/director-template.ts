const outputs: Record<string, string> = { pm: '派单与协作安排', dd: '方向稿', sy: '摄影方案', wz: '动作节拍表',
  art: '光影方案', by: '表演节拍', fx: '特效方案', cj: '连续性检查', sc: '整合交付稿' };
function role(key: string, name: string, responsibilities: string, delivery: string, criteria: string,
  boundary: string, contextGaps: string[] = []) {
  const snapshot: RoleSnapshot = { schema: 'role.v1', name, responsibilities, delivery, criteria,
    boundary: common + '\n' + boundary, executor: { kind: 'unassigned' }, tools: ['manual'], requiredItems: [outputs[key]], workflowOnly: true,
    provenance: ['dd', 'wz', 'art', 'by', 'sc'].includes(key)
      ? { kind: 'designed', version: 'director-minimum.v1.0.0', source: '2026-10-11补充岗位合同；不是找回的Hermes原文' }
      : { kind: 'original', version: 'hermes-role-contexts.v1.0.0', source: '已核Hermes岗位原要求的角色协作适配' },
    ...(contextGaps.length ? { contextGaps } : {}),
    ...(['pm', 'dd', 'cj'].includes(key) ? { reviewAuthority: key === 'pm' ? 'none' : key === 'dd' ? 'final' : 'content' } as const : {}) };
  return { key, snapshot };
}

